"""Command-line interface for AgentReliability.

Commands:
  agentreliability test --project ./tests --output results.json --baseline baseline.json --upload
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional

from .engine import run_test
from .regression import compare_runs


def discover_test_files(project_path: Path) -> List[Path]:
    """Find all .json test files in path or subdirectory."""
    if project_path.is_file():
        return [project_path] if project_path.suffix == ".json" else []
    return sorted(list(project_path.glob("**/*.json")))


def load_test_case(file_path: Path) -> Optional[dict]:
    try:
        data = json.loads(file_path.read_text(encoding="utf-8"))
        if isinstance(data, dict) and "steps" in data:
            if "name" not in data:
                data["name"] = file_path.stem
            return data
    except Exception as e:
        print(f"[Warning] Failed to parse test case {file_path}: {e}", file=sys.stderr)
    return None


def generate_github_summary(report: dict, summary_path: Path) -> None:
    """Write markdown summary to GITHUB_STEP_SUMMARY if present."""
    total = report["total"]
    passed = report["passed"]
    failed = report["failed"]
    reg = report.get("regression", {}).get("counts", {})
    
    md = []
    md.append("# 🤖 AgentReliability AI Test Results\n")
    md.append(f"**Status:** {'✅ All Passed' if failed == 0 else '❌ Regressions / Failures Detected'}\n")
    md.append(f"| Metric | Count |")
    md.append(f"| --- | --- |")
    md.append(f"| Total Tests | {total} |")
    md.append(f"| Passed | {passed} |")
    md.append(f"| Failed | {failed} |")
    if reg:
        md.append(f"| New Failures (Regressions) | {reg.get('new_failures', 0)} |")
        md.append(f"| Fixed Failures | {reg.get('fixed_failures', 0)} |")
        md.append(f"| Unchanged Failures | {reg.get('unchanged_failures', 0)} |")
    md.append("\n")

    if failed > 0:
        md.append("### ❌ Failure Details\n")
        for res in report["results"]:
            if res["status"] == "failed":
                md.append(f"#### Test: `{res['name']}`")
                for m in res["mismatches"]:
                    kind = m.get("kind")
                    step_str = f" (Step {m['step_index'] + 1})" if m.get("step_index") is not None else ""
                    md.append(f"- **{kind}{step_str}:** {m.get('message')}")
                md.append("\n")

    md.append("\n*Report generated by `agentreliability test` CLI.*\n")
    try:
        with open(summary_path, "a", encoding="utf-8") as f:
            f.write("\n".join(md))
    except Exception as e:
        print(f"[Warning] Could not write GitHub step summary: {e}", file=sys.stderr)


def upload_to_backend(report: dict, endpoint: str, api_key: str, commit_sha: Optional[str] = None) -> bool:
    import urllib.request
    import urllib.error

    url = endpoint.rstrip("/") + "/api/v1/ci/runs"
    headers = {
        "Content-Type": "application/json",
        "X-API-Key": api_key
    }
    payload = {
        "commit_sha": commit_sha or os.environ.get("GITHUB_SHA") or "local",
        "branch": os.environ.get("GITHUB_REF_NAME") or "main",
        "actor": os.environ.get("GITHUB_ACTOR") or "local-user",
        "total": report["total"],
        "passed": report["passed"],
        "failed": report["failed"],
        "duration_ms": report["duration_ms"],
        "report": report
    }
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers=headers, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=5.0) as resp:
            return 200 <= resp.status < 300
    except Exception as e:
        print(f"[Warning] Failed to upload CI report to {url}: {e}", file=sys.stderr)
        return False


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="agentreliability",
        description="AgentReliability CLI: automated testing & regression verification."
    )
    subparsers = parser.add_subparsers(dest="command")

    test_parser = subparsers.add_parser("test", help="Discover and execute agent tests.")
    test_parser.add_argument(
        "--project", "-p",
        default="./agent-tests",
        help="Directory containing agent test cases (.json) or path to single file."
    )
    test_parser.add_argument(
        "--output", "-o",
        help="Path to save the output JSON report."
    )
    test_parser.add_argument(
        "--baseline", "-b",
        help="Path to previous JSON test report to perform regression comparison."
    )
    test_parser.add_argument(
        "--upload",
        action="store_true",
        help="Upload CI run results to backend (uses AGENTRELIABILITY_ENDPOINT & AGENTRELIABILITY_API_KEY)."
    )
    test_parser.add_argument(
        "--commit",
        help="Git commit SHA to associate with this CI run."
    )

    args = parser.parse_args(argv)

    if args.command != "test":
        parser.print_help()
        return 1

    project_path = Path(args.project)
    if not project_path.exists():
        print(f"Error: test path '{project_path}' does not exist.", file=sys.stderr)
        return 2

    files = discover_test_files(project_path)
    if not files:
        print(f"No test cases found in '{project_path}'.", file=sys.stderr)
        return 2

    print(f"\n🔍 AgentReliability Test Runner")
    print(f"Discovered {len(files)} test case(s) in '{project_path}'...\n")

    results = []
    started_all = datetime.now(timezone.utc)
    total_duration_ms = 0.0

    for f in files:
        case = load_test_case(f)
        if not case:
            continue
        test_name = case.get("name", f.stem)
        run_res = run_test(case)
        run_res["name"] = test_name
        run_res["file"] = str(f)
        total_duration_ms += run_res.get("duration_ms", 0.0)
        results.append(run_res)

        # Print console status
        if run_res["status"] == "passed":
            print(f"  ✅ PASS: {test_name} ({run_res['duration_ms']:.1f}ms)")
        else:
            print(f"  ❌ FAIL: {test_name} ({run_res['duration_ms']:.1f}ms)")
            for m in run_res.get("mismatches", []):
                step = f" [Step {m['step_index'] + 1}]" if m.get("step_index") is not None else ""
                print(f"       ↳ {m['kind']}{step}: {m['message']}")

    passed_count = sum(1 for r in results if r["status"] == "passed")
    failed_count = sum(1 for r in results if r["status"] == "failed")

    # Regression comparison if baseline provided
    baseline_runs = None
    if args.baseline:
        base_p = Path(args.baseline)
        if base_p.exists():
            try:
                base_data = json.loads(base_p.read_text(encoding="utf-8"))
                baseline_runs = base_data.get("results")
            except Exception as e:
                print(f"[Warning] Failed to load baseline from {base_p}: {e}", file=sys.stderr)

    reg_analysis = compare_runs(results, baseline_runs)

    report = {
        "timestamp": started_all.isoformat(),
        "total": len(results),
        "passed": passed_count,
        "failed": failed_count,
        "duration_ms": round(total_duration_ms, 2),
        "regression": reg_analysis,
        "results": results
    }

    # Summary line
    print(f"\n--------------------------------------------------")
    print(f"Results: {passed_count} passed, {failed_count} failed of {len(results)} total.")
    if reg_analysis.get("has_baseline"):
        c = reg_analysis["counts"]
        print(f"Regression Analysis: {c['new_failures']} new failure(s), {c['fixed_failures']} fixed.")
    print(f"--------------------------------------------------\n")

    # Save output if requested
    if args.output:
        out_p = Path(args.output)
        out_p.parent.mkdir(parents=True, exist_ok=True)
        out_p.write_text(json.dumps(report, indent=2), encoding="utf-8")
        print(f"Report saved to: {out_p}")

    # GitHub Actions Step Summary if in runner environment
    gh_summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if gh_summary:
        generate_github_summary(report, Path(gh_summary))

    # Upload to backend if requested
    if args.upload:
        endpoint = os.environ.get("AGENTRELIABILITY_ENDPOINT", "http://localhost:8000")
        api_key = os.environ.get("AGENTRELIABILITY_API_KEY", "")
        if not api_key:
            print("[Warning] --upload specified but AGENTRELIABILITY_API_KEY is not set.", file=sys.stderr)
        else:
            success = upload_to_backend(report, endpoint, api_key, args.commit)
            if success:
                print("Uploaded test results successfully to AgentReliability backend.")

    # Return exit code 0 if all passed, nonzero if any failed
    return 0 if failed_count == 0 else 1


if __name__ == "__main__":
    sys.exit(main())

